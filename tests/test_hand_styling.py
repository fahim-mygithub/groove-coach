class TestHandStyling(unittest.TestCase):
    def test_fixture_parity_values(self) -> None:
        reference = extract_hand_features(FIXTURES["open"])
        for name, expected in EXPECTED.items():
            is_left, label, orientation, curls, gaps, thumb, normal, confidence, score = expected
            with self.subTest(name=name):
                feats = extract_hand_features(FIXTURES[name], is_left=is_left)
                assert feats is not None
                shape = classify_hand_shape(feats)
                self.assertEqual(shape["label"], label)
                self.assertEqual(feats["palm_orientation"], orientation)
                for a, b in zip(feats["curls"], curls):
                    self.assertAlmostEqual(a, b, delta=1e-9)
                for a, b in zip(feats["gaps"], gaps):
                    self.assertAlmostEqual(a, b, delta=1e-9)
                self.assertAlmostEqual(feats["thumb_extension"], thumb, delta=1e-9)
                for a, b in zip(feats["palm_normal"], normal):
                    self.assertAlmostEqual(a, b, delta=1e-9)
                self.assertAlmostEqual(shape["confidence"], confidence, delta=1e-9)
                self.assertAlmostEqual(compare_hand_features(feats, reference), score, delta=1e-9)

    def test_left_hand_mirrors_to_right(self) -> None:
        right = extract_hand_features(FIXTURES["cupped"])
        left = extract_hand_features(FIXTURES["cupped_left"], is_left=True)
        assert right is not None and left is not None
        self.assertAlmostEqual(compare_hand_features(left, right), 100.0, delta=1e-9)

    def test_scale_and_translation_invariance(self) -> None:
        moved = [(2.0 * x + 5.0, 2.0 * y - 3.0, 2.0 * z + 1.0) for x, y, z in FIXTURES["fist"]]
        a = extract_hand_features(FIXTURES["fist"])
        b = extract_hand_features(moved)
        assert a is not None and b is not None
        self.assertAlmostEqual(compare_hand_features(a, b), 100.0, delta=1e-6)

    def test_identical_is_100_and_different_is_lower(self) -> None:
        open_f = extract_hand_features(FIXTURES["open"])
        fist_f = extract_hand_features(FIXTURES["fist"])
        assert open_f is not None and fist_f is not None
        self.assertAlmostEqual(compare_hand_features(open_f, open_f), 100.0, delta=1e-9)
        self.assertLess(compare_hand_features(open_f, fist_f), 50.0)

    def test_degenerate_input_is_rejected(self) -> None:
        self.assertIsNone(normalize_hand([(0.0, 0.0, 0.0)] * 21))
        self.assertIsNone(extract_hand_features([(0.0, 0.0, 0.0)] * 5))

    def test_feature_ranges(self) -> None:
        for name, pts in FIXTURES.items():
            feats = extract_hand_features(pts)
            assert feats is not None
            for c in feats["curls"]:
                self.assertTrue(0.0 <= c <= 1.0, name)
            self.assertTrue(0.0 <= feats["thumb_extension"] <= 1.0, name)
            self.assertAlmostEqual(math.sqrt(sum(v * v for v in feats["palm_normal"])), 1.0, delta=1e-9)


